#!/usr/bin/env python3
"""
Extract the per-stock tables from an EGX quarterly market report.

The report is generated by Oracle BI Publisher: every stock table page is a
ruled grid, so pdfplumber can recover it cell-by-cell without OCR.

Input:  a PDF path (the file stored under <DOCUMENTS_DIR>/documents/<sha>.pdf)
Output: a single JSON artifact on stdout (or --out PATH):

    {
      "engine": "pdfplumber",
      "engineVersion": "0.11.x",
      "pages": [{"page": 17, "rows": N}],
      "rows": [ {rank, page, rowIndex, rawName, nameAr, ...} ]
    }

The script only reads the PDF. It never writes to the database and never
guesses: values it cannot parse are emitted as null and the importer decides
whether to reject the document.

Column order below is the *visual* left-to-right order produced by pdfplumber
for this template (the document itself is Arabic/RTL, the table cells are not).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import unicodedata

import pdfplumber

ENGINE_VERSION = getattr(pdfplumber, "__version__", "unknown")

# Visual column order in the extracted table.
COLUMNS = [
    "exDate",
    "lastCoupon",
    "netProfitPeriodEnd",
    "netProfit",
    "dividendYield",
    "peTrailing",
    "paidCapital",
    "marketCap",
    "listedShares",
    "tradingVolume",
    "volumePct",
    "tradingValue",
    "changePct",
    "close",
    "currency",
    "rawName",
    "rank",
]

# A page is a stock-table page when the header carries these markers.
HEADER_MARKERS = ("P/E", "DY")

BIDI_AND_CONTROLS = re.compile(
    "[\u200b-\u200f\u202a-\u202e\u2066-\u2069\ufeff]"
)
TATWEEL = "\u0640"
ARABIC_DIACRITICS = re.compile("[\u0610-\u061a\u064b-\u065f\u0670\u06d6-\u06ed]")


def clean_text(value: str | None) -> str:
    if not value:
        return ""
    text = BIDI_AND_CONTROLS.sub("", value)
    text = text.replace(TATWEEL, "")
    text = ARABIC_DIACRITICS.sub("", text)
    return re.sub(r"\s+", " ", text).strip()


ARABIC_RANGES = (
    ("\u0600", "\u06ff"),  # Arabic
    ("\u0750", "\u077f"),  # Arabic Supplement
    ("\u08a0", "\u08ff"),  # Arabic Extended-A
    ("\ufb50", "\ufdff"),  # Arabic Presentation Forms-A
    ("\ufe70", "\ufeff"),  # Arabic Presentation Forms-B
)


def _is_arabic(token: str) -> bool:
    # The PDF stores glyphs as presentation forms (U+FE70..U+FEFF), not base
    # Arabic letters, so both ranges must count.
    return any(
        low <= char <= high for char in token for low, high in ARABIC_RANGES
    )


def _demirror_line(line: str) -> str:
    """
    One visual line -> logical order.

    pdfplumber emits each line in visual (mirrored) order: the words are
    reversed and the Arabic glyphs are reversed, while Latin runs stay
    readable. Reversing the token order and each Arabic token restores it.
    """
    tokens = [token for token in line.split() if token]
    tokens.reverse()
    return " ".join(token[::-1] if _is_arabic(token) else token for token in tokens)


def arabic_logical_order(value: str | None) -> str:
    """
    Arabic cells come back mirrored, and long names wrap onto several lines.
    Each line is de-mirrored on its own so wrapped names stay in reading order.
    NFKC is applied last: it expands ligatures such as lam-alef (U+FEFB) into
    two codepoints, which must not be reversed afterwards.
    """
    if not value:
        return ""
    text = BIDI_AND_CONTROLS.sub("", value)
    text = text.replace(TATWEEL, "")
    text = ARABIC_DIACRITICS.sub("", text)
    lines = [_demirror_line(line) for line in text.splitlines()]
    return unicodedata.normalize("NFKC", " ".join(line for line in lines if line)).strip()


CURRENCIES = {"EGP", "USD", "EUR", "SAR", "AED", "GBP"}


def parse_currency(value: str | None) -> str | None:
    """Some rows emit the currency code reversed (`DSU` for USD)."""
    text = clean_text(value).upper()
    if not text:
        return None
    if text in CURRENCIES:
        return text
    reversed_text = text[::-1]
    if reversed_text in CURRENCIES:
        return reversed_text
    return text


def parse_number(value: str | None) -> float | None:
    text = clean_text(value)
    if not text:
        return None
    text = text.replace(",", "").replace("\u066b", ".").replace("\u066c", ",")
    text = text.replace("EGP", "").replace("USD", "").strip()
    negative = text.startswith("(") and text.endswith(")")
    if negative:
        text = text[1:-1]
    text = text.rstrip("%").strip()
    if not text or text in {"-", "—"}:
        return None
    try:
        number = float(text)
    except ValueError:
        return None
    return -number if negative else number


def parse_date(value: str | None) -> str | None:
    """DD/MM/YYYY -> YYYY-MM-DD. Returns None when the cell is empty."""
    text = clean_text(value)
    if not text:
        return None
    match = re.fullmatch(r"(\d{1,2})/(\d{1,2})/(\d{4})", text)
    if not match:
        return None
    day, month, year = match.groups()
    return f"{year}-{int(month):02d}-{int(day):02d}"


def is_stock_table(table: list[list[str | None]]) -> bool:
    if not table or len(table[0]) < 15:
        return False
    header = " ".join(clean_text(cell) for cell in table[0])
    return all(marker in header for marker in HEADER_MARKERS)


def parse_page(
    page_no: int,
    table: list[list[str | None]],
    segment: str,
) -> list[dict]:
    rows: list[dict] = []
    for row_index, raw in enumerate(table[1:]):
        cells = list(raw) + [None] * (len(COLUMNS) - len(raw))
        record = dict(zip(COLUMNS, cells))

        rank = parse_number(record["rank"])
        name = arabic_logical_order(record["rawName"])
        # Continuation / spacer rows have no rank or no security name.
        if rank is None or not name:
            continue

        rows.append(
            {
                "rank": int(rank),
                "page": page_no,
                "rowIndex": row_index,
                "rawName": clean_text(record["rawName"]),
                "nameAr": name,
                "segment": segment,
                "currency": parse_currency(record["currency"]),
                "close": parse_number(record["close"]),
                "changePct": parse_number(record["changePct"]),
                "tradingValue": parse_number(record["tradingValue"]),
                "tradingVolume": parse_number(record["tradingVolume"]),
                "volumePct": parse_number(record["volumePct"]),
                "listedShares": parse_number(record["listedShares"]),
                "marketCap": parse_number(record["marketCap"]),
                "paidCapital": parse_number(record["paidCapital"]),
                "peTrailing": parse_number(record["peTrailing"]),
                "dividendYield": parse_number(record["dividendYield"]),
                "netProfit": parse_number(record["netProfit"]),
                "netProfitPeriodEnd": parse_date(record["netProfitPeriodEnd"]),
                "lastCoupon": parse_number(record["lastCoupon"]),
                "exDate": parse_date(record["exDate"]),
            }
        )
    return rows


def extract(pdf_path: str) -> dict:
    rows: list[dict] = []
    pages: list[dict] = []
    total_pages = 0

    with pdfplumber.open(pdf_path) as pdf:
        total_pages = len(pdf.pages)
        for index, page in enumerate(pdf.pages):
            page_no = index + 1
            tables = page.extract_tables()
            if not tables:
                continue
            # Page titles are reversed like the cells; reverse them to read.
            page_text = arabic_logical_order(page.extract_text())
            segment = "sme" if "الصغيرة والمتوسطة" in page_text else "main"
            for table in tables:
                if not is_stock_table(table):
                    continue
                page_rows = parse_page(page_no, table, segment)
                if page_rows:
                    rows.extend(page_rows)
                    pages.append(
                        {"page": page_no, "segment": segment, "rows": len(page_rows)}
                    )
                break

    return {
        "engine": "pdfplumber",
        "engineVersion": ENGINE_VERSION,
        "totalPages": total_pages,
        "pages": pages,
        "rows": rows,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pdf", help="path to the report PDF")
    parser.add_argument("--out", help="write JSON here instead of stdout")
    args = parser.parse_args()

    try:
        artifact = extract(args.pdf)
    except Exception as error:  # noqa: BLE001 - report a clean message upstream
        print(f"extract_report: {type(error).__name__}: {error}", file=sys.stderr)
        return 1

    payload = json.dumps(artifact, ensure_ascii=False, indent=1)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as handle:
            handle.write(payload)
    else:
        print(payload)

    if not artifact["rows"]:
        print("extract_report: no stock rows found", file=sys.stderr)
        return 2

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
